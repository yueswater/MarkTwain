import { BULLET_SYMBOLS, ORDERED_STYLES, STATEMENT_KINDS, type StatementStyle } from "@marktwain/schema";
import { escapeTex } from "./escape";

/** The enumitem label of a Typst numbering pattern at a list level, the counter of the level is enumi, enumii and so on. */
function orderedLabel(pattern: string, level: number): string {
  const counter = `enum${["i", "ii", "iii", "iv"][level - 1]}`;
  const number: Record<string, string> = {
    "1": `\\arabic{${counter}}`,
    "①": `\\mtcircled{${counter}}`,
    a: `\\alph{${counter}}`,
    A: `\\Alph{${counter}}`,
    i: `\\roman{${counter}}`,
    I: `\\Roman{${counter}}`,
    一: `\\chinese{${counter}}`,
  };
  return pattern.replace(/[1①aAiI一]/, (symbol) => number[symbol] ?? symbol);
}

/**
 * The LaTeX helpers of MarkTwain, written to the root of every generated project and read by main.tex: the blocks of a mathematical thesis,
 * the markers of lists, strike through, inline code and the landscape pages. Numbers run through the thesis, each kind on its own counter,
 * and a reference writes the name of the kind and the number. The page stays plain, colors exist only in the editor.
 */
export function renderStatementsLatex(style: StatementStyle, lists: { ordered: string[] | null; bullet: string[] | null } = { ordered: null, bullet: null }): string {
  const kinds = STATEMENT_KINDS.map((kind) => {
    const name = escapeTex(style.names[kind.id] ?? kind.id);
    const counter = kind.numbered ? `\\newcounter{mt@${kind.id}}\n` : "";
    return `${counter}\\expandafter\\def\\csname mt@name@${kind.id}\\endcsname{${name}}\n\\expandafter\\def\\csname mt@numbered@${kind.id}\\endcsname{${kind.numbered ? 1 : 0}}`;
  });
  const patterns = (lists.ordered ?? []).map((id) => ORDERED_STYLES.find((s) => s.id === id)?.pattern).filter((p): p is string => p !== undefined);
  const symbols = (lists.bullet ?? []).map((id) => BULLET_SYMBOLS.find((s) => s.id === id)?.symbol).filter((s): s is string => s !== undefined);
  // A list deeper than the levels starts again from the first, enumitem knows four levels
  const orderedSettings = patterns.length > 0 ? [1, 2, 3, 4].map((level) => `\\setlist[enumerate,${level}]{label=${orderedLabel(patterns[(level - 1) % patterns.length] as string, level)}}`) : [];
  const bulletSettings = symbols.length > 0 ? [1, 2, 3, 4].map((level) => `\\setlist[itemize,${level}]{label=${escapeTex(symbols[(level - 1) % symbols.length] as string)}}`) : [];

  return `% Generated by MarkTwain, change the settings of the thesis instead of this file.
\\RequirePackage{xeCJKfntef}
\\RequirePackage{pdflscape}
\\makeatletter

% strike through, for Chinese and Latin text alike
\\DeclareRobustCommand\\mtstrike[1]{\\CJKsout{#1}}

% inline code, set from escaped text so it can stand inside captions and notes
\\DeclareRobustCommand\\mtcode[1]{{\\xeCJKsetup{CJKecglue={}}\\ttfamily\\color{twcodeblue}#1}}

% the text of a table at a share of the size of the text of the page
\\newcommand\\mtscale[1]{\\fontsize{\\fpeval{#1*\\f@size}}{\\fpeval{#1*\\f@baselineskip}}\\selectfont}

% the caption of a listing goes where the settings say, the template hands that to listings as a macro that is read too late
\\twifstr{\\twget{d.caption.code}}{top}{\\lstset{captionpos=t}}{\\lstset{captionpos=b}}

% listings are counted through the thesis like figures and tables, the chapter is not part of the number
\\AtBeginDocument{\\counterwithout{lstlisting}{chapter}}

% the label of the notes under a table, for a table that runs over pages and has no tlt around it
\\newcommand\\mtnoteslabel{\\tw@tblnoteslabel@default}

% a circled number, one to fifty
\\newcommand\\mtcircled[1]{%
  \\ifnum\\value{#1}<21 \\symbol{\\numexpr"245F+\\value{#1}\\relax}%
  \\else\\ifnum\\value{#1}<36 \\symbol{\\numexpr"3250+\\value{#1}-20\\relax}%
  \\else\\ifnum\\value{#1}<51 \\symbol{\\numexpr"32B0+\\value{#1}-35\\relax}%
  \\else\\arabic{#1}\\fi\\fi\\fi}

${orderedSettings.join("\n")}${orderedSettings.length > 0 ? "\n" : ""}${bulletSettings.join("\n")}${bulletSettings.length > 0 ? "\n" : ""}
${kinds.join("\n")}

\\newcommand\\mt@statementname[1]{\\csname mt@name@#1\\endcsname}

% One block, the arguments are the kind, the title and the label, which is empty for none
\\newenvironment{mtstatement}[3]{%
  \\par\\addvspace{1.3em}\\begingroup\\setlength\\parindent{0pt}%
  \\def\\mt@kind{#1}%
  \\ifnum\\csname mt@numbered@#1\\endcsname=1
    \\refstepcounter{mt@#1}\\if\\relax\\detokenize{#3}\\relax\\else\\label{#3}\\fi
    \\textbf{\\mt@statementname{#1} \\csname themt@#1\\endcsname}%
  \\else
    \\textbf{\\mt@statementname{#1}}%
  \\fi
  \\if\\relax\\detokenize{#2}\\relax\\else\\textbf{（#2）}\\fi
  \\par}{%
  \\ifx\\mt@kind\\mt@proofkind\\hfill\\ensuremath{\\square}\\fi
  \\endgroup\\par\\addvspace{1.3em}}
\\def\\mt@proofkind{proof}

% A reference to a block writes the name of its kind and its number
\\newcommand\\mtstatementref[2]{\\mt@statementname{#1}~\\ref{#2}}
\\makeatother
`;
}
