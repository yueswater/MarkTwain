import { BULLET_SYMBOLS, ORDERED_STYLES, STATEMENT_KINDS, type StatementStyle } from "@marktwain/schema";
import { escapeString } from "./escape";

/**
 * The Typst helpers of MarkTwain, written to the root of every generated project: the blocks of a mathematical thesis, which are drawn
 * as definitions, lemmas, theorems and the like, and the markers of the preview.
 * Numbers run through the thesis, each kind on its own counter, and a reference reads the kind from the block it points at.
 * The page stays plain, colors exist only in the editor.
 */
export function renderStatementsTypst(style: StatementStyle, lists: { ordered: string[] | null; bullet: string[] | null } = { ordered: null, bullet: null }): string {
  const patterns = (lists.ordered ?? []).map((id) => ORDERED_STYLES.find((s) => s.id === id)?.pattern).filter((p): p is string => p !== undefined);
  const symbols = (lists.bullet ?? []).map((id) => BULLET_SYMBOLS.find((s) => s.id === id)?.symbol).filter((s): s is string => s !== undefined);
  const kinds = STATEMENT_KINDS.map((kind) => {
    const name = style.names[kind.id] ?? kind.id;
    return `  ${kind.id}: (name: "${escapeString(name)}", numbered: ${kind.numbered}),`;
  });
  return `// Generated by MarkTwain, change the settings of the thesis instead of this file.

// The marker of each level of a list, a list deeper than the levels starts again from the first
${patterns.length > 0 ? `#let mt-enum-styles = (${patterns.map((p) => `"${escapeString(p)}"`).join(", ")},)
#let mt-enum-numbering = (..number) => {
  let all = number.pos()
  numbering(mt-enum-styles.at(calc.rem(all.len() - 1, mt-enum-styles.len())), all.last())
}
` : ""}${symbols.length > 0 ? `#let mt-list-markers = (${symbols.map((s) => `[${escapeString(s)}]`).join(", ")},)
` : ""}
// A landscape page for wide tables, the page number stays at the foot of the turned page and a table that is too long goes on to the next one.
// A heading of level 1 inside would start a new chapter page and leave an empty one before it, so it is drawn without that.
#let mt-landscape(body) = page(flipped: true, margin: (x: 1.5cm, y: 1.2cm))[
  #show figure: set block(breakable: true)
  #show heading.where(level: 1): it => {
    set align(center)
    set text(size: 18pt, weight: "regular")
    v(0.5em)
    it.body
    v(1em)
  }
  #body
]

// Where a block of the editor landed on the page, read back with typst query for the preview that follows the editor
#let mtpos(id) = context [#metadata((id: id, page: here().page(), y: here().position().y.pt())) <mtpos>]

#let statement-kinds = (
${kinds.join("\n")}
)

#let statement-counter(kind) = counter("statement-" + kind)

// One block, kind is a key of statement-kinds, id the label without the angle brackets
#let statement(kind, id: none, title: none, body) = {
  let info = statement-kinds.at(kind)
  if info.numbered { statement-counter(kind).step() }
  let anchor = if id == none { metadata(kind) } else { [#metadata(kind)#label(id)] }
  let head = context {
    let number = if info.numbered { [ #statement-counter(kind).get().first()] } else { [] }
    let name = if title == none { [] } else { [（#title）] }
    strong[#info.name#number#name]
  }
  let end = if kind == "proof" { align(right, sym.square.stroked) } else { none }
  anchor
  block(width: 100%, breakable: true, above: 1.3em, below: 1.3em, {
    set par(first-line-indent: 0em)
    head
    parbreak()
    body
    end
  })
}

// A reference to a block, the kind and the number come from the block itself
#let statement-ref(target) = context {
  let found = query(target)
  if found.len() == 0 { return ref(target) }
  let kind = found.first().value
  let info = statement-kinds.at(kind)
  let number = statement-counter(kind).at(found.first().location()).first()
  link(target, [#info.name #number])
}
`;
}
